def rnd(x):
    if isinstance(x, dict):
        return {k: rnd(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [rnd(v) for v in x]
    if isinstance(x, (bool, np.bool_)):
        return bool(x)
    if isinstance(x, (np.integer,)):
        return int(x)
    if isinstance(x, (float, np.floating)):
        return None if np.isnan(x) else round(float(x), 4)
    return x


def jload(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def top_pos(df, col, k=5):
    """Top-k rows with a strictly positive value (df already sorted descending by col)."""
    return df[df[col] > 0].sort_values(col, ascending=False, kind="mergesort").head(k)


def bottom_neg(df, col, k=5):
    """Bottom-k rows with a strictly negative value, most negative first."""
    return df[df[col] < 0].sort_values(col, ascending=True, kind="mergesort").head(k)


def records(df, cols, rename=None):
    out = df[cols].rename(columns=rename or {})
    return [{k: (v.item() if hasattr(v, "item") else v) for k, v in r.items()} for r in out.to_dict("records")]


def _zero(rep):
    out = {"n_coef_total": rep["n_coef_total"], "n_coef_zero": rep["n_coef_zero"],
           "n_onehot_total": rep["n_onehot_total"], "n_onehot_zero": rep["n_onehot_zero"]}
    out["levels_zeroed_by_group"] = {c: {"zero": rep[f"{c}_levels_zero"], "total": rep[f"{c}_levels_total"]}
                                     for c in ("country", "province", "variety")}
    out["group_most_levels_zeroed"] = max(("country", "province", "variety"),
                                          key=lambda c: (rep[f"{c}_levels_zero"], c))
    return out


